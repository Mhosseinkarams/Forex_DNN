import logging
from typing import Dict, List, Any, Tuple
import pandas as pd
import numpy as np

logger = logging.getLogger("DatasetValidator")


class DatasetValidator:
    """
    Validates machine learning datasets generated by HistoricalDatasetBuilder.
    Checks for missing values, infinite values, duplicates, timestamp consistency,
    window alignment, class/symbol imbalance, low-variance, high feature correlation,
    outliers, dataset leakage, and window overlap problems.
    Produces a detailed ValidationReport.
    """

    def __init__(
        self,
        critical_missing_threshold: float = 0.0,
        max_duplicate_ratio: float = 0.01,
        low_variance_threshold: float = 1e-5,
        correlation_threshold: float = 0.98,
        outlier_z_threshold: float = 5.0
    ):
        """
        Args:
            critical_missing_threshold: Max allowed fraction of missing values before a critical error.
            max_duplicate_ratio: Max allowed duplicate ratio before a warning.
            low_variance_threshold: Variance below which a numeric column is flagged as low variance.
            correlation_threshold: Pearson correlation above which feature pairs are flagged as redundant.
            outlier_z_threshold: Z-score above which a feature value is flagged as an outlier.
        """
        self.critical_missing_threshold = critical_missing_threshold
        self.max_duplicate_ratio = max_duplicate_ratio
        self.low_variance_threshold = low_variance_threshold
        self.correlation_threshold = correlation_threshold
        self.outlier_z_threshold = outlier_z_threshold

    def validate(self, df: pd.DataFrame, expected_window_size: int = 35) -> Dict[str, Any]:
        """
        Validates the generated dataset.

        Args:
            df: The generated labeled DataFrame.
            expected_window_size: The window size used to generate the dataset.

        Returns:
            Dict: Detailed validation report with status, errors, warnings, and metrics.
        """
        report = {
            "is_valid": True,
            "errors": [],
            "warnings": [],
            "metrics": {
                "total_samples": len(df),
                "columns_count": len(df.columns) if not df.empty else 0,
                "missing_values_by_column": {},
                "duplicate_rows": 0,
                "class_distribution": {},
                "symbols": [],
                "timeframes": []
            }
        }

        if df.empty:
            report["is_valid"] = False
            report["errors"].append("The dataset is empty.")
            return report

        # Extract symbols and timeframes
        symbols = df["symbol"].unique().tolist() if "symbol" in df.columns else []
        timeframes = df["timeframe"].unique().tolist() if "timeframe" in df.columns else []
        report["metrics"]["symbols"] = symbols
        report["metrics"]["timeframes"] = timeframes

        # 1. Missing / NaN Values Check
        null_counts = df.isnull().sum()
        total_rows = len(df)
        has_critical_missing = False

        for col, count in null_counts.items():
            if count > 0:
                fraction = count / total_rows
                report["metrics"]["missing_values_by_column"][col] = int(count)

                # Check if this column is critical (target, confidence, symbol, timeframe, or datetime)
                is_critical_col = col in ["target", "confidence", "symbol", "timeframe", "datetime", "sample_id"]
                if is_critical_col or fraction > self.critical_missing_threshold:
                    msg = f"Column '{col}' has {count} missing values ({fraction:.2%})."
                    if is_critical_col:
                        report["errors"].append(msg)
                        has_critical_missing = True
                    else:
                        report["warnings"].append(msg)

        # Missing labels check
        if "target" in df.columns:
            missing_labels = df["target"].isnull().sum()
            if missing_labels > 0:
                report["errors"].append(f"Detected {missing_labels} samples with missing target labels.")
                has_critical_missing = True

        if has_critical_missing:
            report["is_valid"] = False

        # 2. Infinite Values Check
        numeric_cols = df.select_dtypes(include=[np.number]).columns
        for col in numeric_cols:
            inf_mask = np.isinf(df[col])
            inf_count = int(inf_mask.sum())
            if inf_count > 0:
                report["errors"].append(f"Column '{col}' contains {inf_count} infinite values.")
                report["is_valid"] = False

        # 3. Duplicate Rows Check
        dup_mask = df.duplicated()
        dup_count = int(dup_mask.sum())
        report["metrics"]["duplicate_rows"] = dup_count

        if dup_count > 0:
            dup_ratio = dup_count / total_rows
            msg = f"Detected {dup_count} duplicate rows ({dup_ratio:.2%})."
            if dup_ratio > self.max_duplicate_ratio:
                report["errors"].append(msg)
                report["is_valid"] = False
            else:
                report["warnings"].append(msg)

        # 4. Duplicate IDs Check
        if "sample_id" in df.columns:
            id_dup_count = int(df["sample_id"].duplicated().sum())
            if id_dup_count > 0:
                report["errors"].append(f"Detected {id_dup_count} duplicate sample_ids inside the dataset.")
                report["is_valid"] = False

        # 5. Duplicate Timestamps per symbol/timeframe Check
        if "symbol" in df.columns and "timeframe" in df.columns and "datetime" in df.columns:
            ts_dup_mask = df.duplicated(subset=["symbol", "timeframe", "datetime"])
            ts_dup_count = int(ts_dup_mask.sum())
            if ts_dup_count > 0:
                report["errors"].append(f"Detected {ts_dup_count} duplicate timestamps for the same symbol/timeframe combination.")
                report["is_valid"] = False

        # 6. Low Variance and Constant Columns Check
        # Exclude metadata / targets
        metadata_cols = ["target", "confidence", "window_start", "window_end", "Open", "High", "Low", "Close", "TickVolume", "ema_50", "ema_600", "ema_800", "sample_id", "symbol", "timeframe", "datetime"]
        feature_cols = [c for c in numeric_cols if c not in metadata_cols]

        constant_columns = []
        low_variance_columns = []
        for col in feature_cols:
            non_null_vals = df[col].dropna()
            if non_null_vals.empty:
                continue
            var = float(non_null_vals.var())
            if var == 0 or non_null_vals.nunique() <= 1:
                constant_columns.append(col)
            elif var < self.low_variance_threshold:
                low_variance_columns.append(col)

        if constant_columns:
            report["warnings"].append(f"Constant columns detected (variance=0): {constant_columns}")
        if low_variance_columns:
            report["warnings"].append(f"Low variance columns detected (< {self.low_variance_threshold}): {low_variance_columns}")

        # 7. Class Imbalance Check
        if "target" in df.columns:
            class_counts = df["target"].value_counts().to_dict()
            class_dist = {str(k): int(v) for k, v in class_counts.items()}
            report["metrics"]["class_distribution"] = class_dist

            for regime in ["TREND", "RANGE", "TRANSITION"]:
                count = class_dist.get(regime, 0)
                if count == 0:
                    report["warnings"].append(f"Class '{regime}' is completely missing from the labeled dataset.")
                elif count / total_rows < 0.01:
                    report["warnings"].append(f"Class '{regime}' represents less than 1% of the dataset (extreme class imbalance).")

        # 8. Symbol Imbalance Check
        if "symbol" in df.columns:
            sym_counts = df["symbol"].value_counts()
            for sym, count in sym_counts.items():
                ratio = count / total_rows
                if ratio > 0.8:
                    report["warnings"].append(f"Symbol '{sym}' dominates the dataset with {ratio:.1%} of all samples.")

        # 9. Feature Correlation Check
        if len(feature_cols) > 1 and len(df) > 5:
            # Drop constant columns first to avoid NaN correlations
            active_feat_cols = [c for c in feature_cols if c not in constant_columns]
            if len(active_feat_cols) > 1:
                try:
                    corr_matrix = df[active_feat_cols].corr().abs()
                    upper_tri = corr_matrix.where(np.triu(np.ones(corr_matrix.shape), k=1).astype(bool))
                    to_drop = [column for column in upper_tri.columns if any(upper_tri[column] > self.correlation_threshold)]
                    if to_drop:
                        report["warnings"].append(f"Highly correlated feature pairs detected (r > {self.correlation_threshold}). Redundant features: {to_drop[:10]}")
                except Exception as e:
                    logger.debug(f"Correlation check failed: {e}")

        # 10. Outlier Detection (Z-score based)
        outliers_detected = {}
        for col in feature_cols:
            if col in constant_columns:
                continue
            vals = df[col].dropna()
            if vals.empty:
                continue
            mean = vals.mean()
            std = vals.std()
            if std > 0:
                z_scores = (vals - mean).abs() / std
                outlier_count = int((z_scores > self.outlier_z_threshold).sum())
                if outlier_count > 0:
                    outliers_detected[col] = outlier_count

        if outliers_detected:
            # Report first 10 columns with outliers
            outlier_summary = {k: v for k, v in list(outliers_detected.items())[:10]}
            report["warnings"].append(f"Outliers detected (Z-score > {self.outlier_z_threshold}) in features: {outlier_summary}")

        # 11. Dataset Leakage Check
        # Check if feature names contain "target" or other lookahead keywords
        leakage_cols = [c for c in df.columns if any(kw in c.lower() for kw in ["future", "lookahead", "next_bar", "tomorrow"])]
        if leakage_cols:
            report["errors"].append(f"Potential dataset leakage: Columns with future/lookahead naming found: {leakage_cols}")
            report["is_valid"] = False

        # 12. Window Consistency & Overlap Problems Check
        if "window_start" in df.columns and "window_end" in df.columns:
            computed_sizes = df["window_end"] - df["window_start"] + 1
            mismatches = computed_sizes != expected_window_size
            mismatch_count = int(mismatches.sum())
            if mismatch_count > 0:
                report["errors"].append(f"Detected {mismatch_count} rows with inconsistent window sizes. Expected size {expected_window_size}.")
                report["is_valid"] = False

            # Check window progression per symbol and timeframe group
            if "symbol" in df.columns and "timeframe" in df.columns:
                for (sym, tf), group in df.groupby(["symbol", "timeframe"]):
                    starts = group["window_start"].values
                    if len(starts) > 1:
                        diffs = np.diff(starts)
                        if (diffs <= 0).any():
                            report["warnings"].append(f"Window starts do not strictly increase for {sym} {tf}. Stride might be negative or random.")

        # Timestamp Consistency (monotonic increasing per symbol and timeframe)
        if "datetime" in df.columns and "symbol" in df.columns and "timeframe" in df.columns:
            for (sym, tf), group in df.groupby(["symbol", "timeframe"]):
                dates = pd.to_datetime(group["datetime"])
                if not dates.is_monotonic_increasing:
                    report["errors"].append(f"Timestamps are not monotonically increasing for {sym} {tf}.")
                    report["is_valid"] = False

        return report
